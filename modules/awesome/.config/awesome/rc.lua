-- Battery
local baticon = wibox.widget.imagebox(beautiful.battery)
local bat = lain.widget.bat({
    settings = function()
        local bat_perc = tonumber(bat_now.perc)

        if bat_now.status ~= "N/A" then
            if bat_now.ac_status == 1 then
                widget:set_markup(markup.font(theme.font, " AC "))
                baticon:set_image(beautiful.battery_ac)
                return
            elseif bat_perc and bat_perc <= 5 then
                baticon:set_image(beautiful.battery_empty)
            elseif bat_perc and bat_perc <= 15 then
                baticon:set_image(beautiful.battery_low)
            else
                baticon:set_image(beautiful.battery)
            end
            if bat_perc or bat_now.perc then
                widget:set_markup(markup.font(theme.font, " " .. (bat_perc or bat_now.perc) .. "% "))
            else
                widget:set_markup(markup.font(theme.font, " N/A "))
            end
        else
            widget:set_markup(markup.font(theme.font, " AC "))
            baticon:set_image(beautiful.battery_ac)
        end
    end
})

